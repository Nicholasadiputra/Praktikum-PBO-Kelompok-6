    private void initTable() {
        // 1. Siapkan Model Tabel Baru
        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel();
        
        // 2. Buat Judul Kolom
        model.addColumn("Nama Produk");
        model.addColumn("Harga");

        // 3. LOOPING DATA GLOBAL (Ini bagian intinya)
        // Mengambil semua data dari gudang data (DataGlobal) satu per satu
        for (String[] produk : com.kedaikasir.model.DataGlobal.daftarProduk) {
            
            // Masukkan data ke dalam baris tabel
            // produk[0] adalah Nama, produk[1] adalah Harga
            model.addRow(produk); 
        }

        // 4. Pasang Model yang sudah diisi ke Tabel Visual (tblProduk)
        // Pastikan nama variabel tabel Anda benar (tblProduk atau jTable1)
        tblProduk.setModel(model); 
    }
