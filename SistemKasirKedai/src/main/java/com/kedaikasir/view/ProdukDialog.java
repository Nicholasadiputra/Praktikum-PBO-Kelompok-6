    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        String nama = txtNama.getText();
        String harga = txtHarga.getText();

        if (nama.isEmpty() || harga.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Isi nama dan harga dulu!");
            return;
        }

        // --- LOGIKA CERDAS: CEK APAKAH PRODUK SUDAH ADA? ---
        boolean ditemukan = false;

        // Loop data global untuk mencari nama yang sama
        for (String[] produk : com.kedaikasir.model.DataGlobal.daftarProduk) {
            // Cek kesamaan nama (equalsIgnoreCase biar tidak peduli huruf besar/kecil)
            if (produk[0].equalsIgnoreCase(nama)) {
                // KETEMU! Berarti ini UPDATE harga
                produk[1] = harga; // Ganti harga lama dengan yang baru
                ditemukan = true;
                break; // Berhenti mencari
            }
        }

        // Jika tidak ditemukan, berarti ini PRODUK BARU
        if (!ditemukan) {
            com.kedaikasir.model.DataGlobal.daftarProduk.add(new String[]{nama, harga});
        }

        // --- AKHIR LOGIKA ---

        // Refresh tabel di dialog ini
        initTable(); // Panggil ulang initTable untuk memuat data terbaru

        // Reset Form
        txtNama.setText("");
        txtHarga.setText("");
        txtNama.requestFocus();

        javax.swing.JOptionPane.showMessageDialog(this, "Data Berhasil Disimpan!");
    }//GEN-LAST:event_btnSimpanActionPerformed

