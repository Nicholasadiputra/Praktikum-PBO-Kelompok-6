    private void kirimButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_kirimButtonActionPerformed
        String nama = namaTextField.getText();
        String nim = nimTextField.getText();
        String prodi = (String) prodiComboBox.getSelectedItem();
        
        // 1. Validasi string kosong
        if (nama.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama tidak boleh kosong!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        if (nim.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "NIM tidak boleh kosong!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // 2. Validasi NIM harus angka
        if (!nim.matches("\\d+")) {
            JOptionPane.showMessageDialog(this, "NIM harus berupa angka!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // 3. Validasi jenis kelamin
        String jenisKelamin = null;
        if (lakilakiRadioButton.isSelected()) {
            jenisKelamin = "Laki-Laki";
        } else if (perempuanRadioButton.isSelected()) {
            jenisKelamin = "Perempuan";
        } else {
            JOptionPane.showMessageDialog(this, "Jenis kelamin harus dipilih!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        boolean isActive = aktifCheckBox.isSelected();
        // --- AKHIR VALIDASI ---

        // Cek apakah ini mode "Update" atau "Create"
        if (mahasiswaToUpdate != null) {
            // --- LOGIKA UPDATE ---
            // Set data baru ke objek mahasiswa yang sudah ada
            mahasiswaToUpdate.setNama(nama);
            mahasiswaToUpdate.setProdi(prodi);
            mahasiswaToUpdate.setJenisKelamin(jenisKelamin);
            mahasiswaToUpdate.setActive(isActive);
            // NIM tidak di-set karena tidak boleh diubah
            
            JOptionPane.showMessageDialog(this, "Sukses memperbarui data mahasiswa " + nama);
            
            // Kembali ke panel LihatDataPanel
            MainJFrame parentFrame = (MainJFrame) SwingUtilities.getWindowAncestor(this);
            if (parentFrame != null) {
                parentFrame.changeMainPanel(new LihatDataPanel());
            }
            
        } else {
            // --- LOGIKA CREATE ---
            
            // 4. Validasi NIM duplikat (hanya saat create)
            if (isNimExists(nim)) {
                JOptionPane.showMessageDialog(this, "NIM " + nim + " sudah terdaftar!", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Buat objek baru jika semua validasi lolos
            Mahasiswa mahasiswa = new Mahasiswa(nama, nim, prodi, jenisKelamin, isActive);
            Mahasiswa.mahasiswas.add(mahasiswa);

            JOptionPane.showMessageDialog(this, "Sukses menambahkan data mahasiswa " + nama);
            clearForm();
        }
    }//GEN-LAST:event_kirimButtonActionPerformed


